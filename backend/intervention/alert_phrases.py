def is_supported_language(lang: str) -> bool:
    return lang in SUPPORTED_LANGUAGES


def has_translation(scenario: Optional[str], lang: str) -> bool:
    """True when a reviewed (non-English-fallback) phrase exists for this
    scenario in this language."""
    if lang == DEFAULT_LANGUAGE:
        return True
    bank = SPOKEN_ALERTS.get(scenario or "") or {}
    return lang in bank


def alert_text(scenario: Optional[str], lang: str, *, fallback: Optional[str] = None) -> str:
    """Spoken instruction for `scenario` in `lang`.

    Falls back, in order: the scenario's English phrase, the caller-supplied
    `fallback` (e.g. an alert's own `immediate_action` text), then the
    generic phrase — always in the requested language, never silently
    switching language on fallback.
    """
    lang = lang if is_supported_language(lang) else DEFAULT_LANGUAGE
    bank = SPOKEN_ALERTS.get(scenario or "")
    if bank:
        if lang in bank:
            return bank[lang]
        if fallback:
            return fallback
        return bank.get(DEFAULT_LANGUAGE, GENERIC_ALERT[DEFAULT_LANGUAGE])
    if fallback:
        return fallback
    return GENERIC_ALERT.get(lang, GENERIC_ALERT[DEFAULT_LANGUAGE])
